/**
 * Configuration & Secrets Recovery v1 — canonical configuration recovery
 * register. See docs/configuration-and-secrets-recovery-v1.md.
 *
 * VALUE-FREE BY DESIGN: this file is metadata only. Nothing in
 * `ConfigRecoveryEntry` can hold an actual secret value, example
 * Production value, hash, fingerprint, or ciphertext — there is no
 * `value`/`secret`/`passwordValue`/`privateKeyValue`/`tokenValue` field
 * anywhere on this type, and there never should be (see
 * `register.test.ts`'s own structural guard for this). Every entry below
 * is grounded in either a real `process.env.<NAME>` read site in this
 * repository or an existing, already-reviewed document — never guessed
 * from a plausible-sounding name.
 *
 * This register deliberately keeps THREE separate concepts apart (see
 * docs/configuration-and-secrets-recovery-v1.md, "Three different
 * concepts" for the full explanation):
 *
 * 1. `runtimeSource` — where the RUNNING service currently reads the
 *    value from today (e.g. "Vercel project environment variable").
 * 2. `recoveryClass` (+ `lossImpact`/`rotationImpact`) — HOW the value
 *    would be reconstructed after loss.
 * 3. `authoritativeRecoverySourceStatus` — WHERE the recoverable
 *    material is independently held, separate from the runtime. For
 *    every real secret in this register today, that is
 *    `"NOT_YET_SELECTED"` — a Vercel environment variable is a RUNTIME
 *    SOURCE, never treated here as an independent recovery source
 *    merely because it currently holds the value, and GitHub is never
 *    treated as a secret-value recovery source at all (see
 *    docs/configuration-and-secrets-recovery-v1.md's own explicit
 *    statement of this).
 *
 * ALIAS MODEL — one entry's `aliasNames` means ONE thing, always:
 * alternative/fallback representations of the SAME logical
 * configuration value, where the running code checks them in a fixed
 * priority order and only ONE is ever actually expected to be set (the
 * LTI `*_B64`/`*_PATH`/raw key triples; `NEXT_PUBLIC_SUPABASE_URL` as
 * `SUPABASE_URL`'s fallback; `GIT_COMMIT_SHA` as
 * `VERCEL_GIT_COMMIT_SHA`'s fallback). It does NOT mean "these names are
 * read independently but I grouped them to shorten the register" — that
 * was a real modelling error found in an earlier pass (four independent
 * `TETHER_BLOCK_*` lockdown toggles, `LTI_TOOL_NAME`/`LTI_TOOL_DESCRIPTION`,
 * and `SUPABASE_ACCESS_TOKEN`/`SUPABASE_DB_PASSWORD` were all previously
 * mis-grouped this way) — because the audit's own "is this entry
 * represented in `.env.example`" check is satisfied by ANY ONE
 * name/alias being present, so a genuinely independent variable's own
 * deletion from the template could go completely undetected as long as
 * a sibling it was wrongly grouped with remained. Every independent
 * variable now has its own entry with `aliasNames: []`, even where that
 * makes this file longer. `register.test.ts`'s `[12]` test locks every
 * remaining non-empty `aliasNames` group in this file against an
 * explicit allowlist of genuine alternate-representation groups, so a
 * future accidental re-grouping is caught immediately rather than
 * inferred from variable-name similarity.
 */

/** Where the running service currently reads this configuration item's value from. */
export type ConfigCategory =
  | "ACTIVE_PRODUCTION_RUNTIME"
  | "OPTIONAL_PRODUCTION_RUNTIME"
  | "OPERATOR_MAINTENANCE_ONLY"
  | "LOCAL_DEVELOPMENT_ONLY"
  | "PROVIDER_PLATFORM_SUPPLIED"
  | "FUTURE_NOT_PROVISIONED"
  | "DEPRECATED_DOCUMENTED_NOT_USED";

/**
 * HOW this item would be reconstructed after loss — see this file's own
 * doc comment. `null` only for items where a recovery class genuinely
 * does not apply yet (e.g. `FUTURE_NOT_PROVISIONED` items, which have no
 * live value to recover).
 */
export type RecoveryClass = "PRESERVE_EXACT_VALUE" | "ROTATE_OR_REISSUE" | "RECONSTRUCT_CONFIGURATION" | "PROVIDER_LOOKUP" | "BOOTSTRAP_ONLY" | "FUTURE_NOT_PROVISIONED";

/** Whether this item's VALUE (not its name) is sensitive. Never used to decide whether the NAME can appear here — names always can. */
export type ConfigSensitivity = "SECRET" | "NON_SECRET";

/** Where the running service reads this value from today. Deliberately distinct from `authoritativeRecoverySourceStatus` — see this file's own doc comment, concept 1 vs 3. */
export type RuntimeSource = "VERCEL_ENVIRONMENT_VARIABLE" | "LOCAL_OPERATOR_ENVIRONMENT" | "PROVIDER_SUPPLIED_AT_RUNTIME" | "BUILD_TOOLING_SUPPLIED" | "NOT_YET_PROVISIONED" | "NOT_APPLICABLE";

export type ConfigEnvironment = "PRODUCTION_AND_PREVIEW" | "PRODUCTION_ONLY" | "PREVIEW_ONLY" | "LOCAL_ONLY" | "ALL_DEPLOYMENTS" | "NOT_APPLICABLE";

/**
 * Every real secret in this register is currently `"NOT_YET_SELECTED"` —
 * see this file's own doc comment. Kept as a literal union (not a bare
 * string) so a future, deliberate change to the actual set of possible
 * statuses is a visible type change, not a silent string edit.
 */
export type AuthoritativeRecoverySourceStatus = "NOT_YET_SELECTED";

export type ConfigRecoveryEntry = {
  /** The env var name exactly as read via `process.env.<NAME>`. */
  name: string;
  /**
   * ONE meaning, never overloaded: alternative/fallback representations
   * of the SAME logical configuration value — e.g. `LTI_PRIVATE_KEY_B64`
   * / `LTI_PRIVATE_KEY_PATH` / `LTI_PRIVATE_KEY` (checked in that
   * priority order, only ONE is ever actually set), or
   * `NEXT_PUBLIC_SUPABASE_URL` as `SUPABASE_URL`'s fallback. See this
   * module's own "Alias model" doc comment for the full test — the short
   * version: if the running code reads two names INDEPENDENTLY of each
   * other (each with its own default, each meaningfully settable at the
   * same time as the other), they are NOT aliases of one entry — they
   * are two separate `ConfigRecoveryEntry` objects, even if that makes
   * the register longer. Never use this field merely to shorten the
   * register. `register.test.ts`'s own `[12]` test locks every
   * non-empty group in this file against an explicit allowlist, so a
   * future accidental re-grouping is caught immediately, not inferred
   * from name similarity.
   */
  aliasNames: string[];
  category: ConfigCategory;
  sensitivity: ConfigSensitivity;
  environment: ConfigEnvironment;
  runtimeSource: RuntimeSource;
  recoveryClass: RecoveryClass | null;
  /** True if the running application/feature this entry gates cannot function correctly without it — never true merely because a value "should probably" be set. */
  required: boolean;
  /** The specific capability this item affects — never "the app" as a whole unless genuinely core-required. */
  affectedCapability: string;
  /** What becomes unavailable or inconsistent if this value is lost and (where applicable) replaced with a different one. Required for every SECRET entry with a non-null recoveryClass — see register.test.ts. */
  lossImpact: string;
  /** What happens to already-existing data/state if this value is deliberately rotated to a NEW value. `null` only where rotation impact is not a meaningful question for this entry (e.g. a plain non-secret URL). */
  rotationImpact: string | null;
  /** Another register entry name this one's recovery depends on (e.g. `TETHER_SEB_KEY_ENCRYPTION_ACTIVE_KEY_ID` depends on a key of the same id existing in `TETHER_SEB_KEY_ENCRYPTION_KEYS_JSON`). `null` if none. */
  recoveryDependency: string | null;
  /** Whether this NAME is expected to appear in `.env.example` (with a blank/synthetic value) — false for FUTURE_NOT_PROVISIONED items and for platform-auto-supplied build metadata that an operator never sets by hand. */
  templatePresenceExpected: boolean;
  /** File:line or documentation path this entry is grounded in. */
  sourceReference: string;
  /** See this file's own doc comment, concept 3. Every SECRET entry today is `"NOT_YET_SELECTED"`. */
  authoritativeRecoverySourceStatus: AuthoritativeRecoverySourceStatus | null;
  /** Free-text clarification, only when genuinely needed beyond the structured fields above. */
  notes?: string;
};

