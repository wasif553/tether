export function getConfigRecoveryEntry(name: string): ConfigRecoveryEntry {
  const entry = CONFIGURATION_RECOVERY_REGISTER.find((e) => e.name === name || e.aliasNames.includes(name));
  if (!entry) throw new Error(`No configuration recovery register entry for "${name}".`);
  return entry;
}
